import 'dotenv/config';
import { describe, it, expect } from 'vitest';
import { randomUUID } from 'node:crypto';
import bcrypt from 'bcryptjs';
import { ConfigService } from '@nestjs/config';
import { validateSync } from 'class-validator';
import { PrismaService } from '../src/database/prisma.service.js';
import { PlatformService, defaultBranding } from '../src/platform/platform.service.js';
import { CompanyService } from '../src/company/company.service.js';
import { AreaManagementService } from '../src/manager/area-management.service.js';
import { TargetManagementService } from '../src/manager/target-management.service.js';
import { RecurringCycleService } from '../src/cycles/recurring-cycle.service.js';
import { ManagerService } from '../src/manager/manager.service.js';
import { BrandingDto } from '../src/platform/platform.dto.js';
import type { AuthUser } from '../src/auth/auth.types.js';
describe.skipIf(process.env.RUN_DB_TESTS !== '1')('company provisioning and branding', () => {
  it('creates an isolated owner, restricts platform access and versions branding without exposing secrets', async () => {
    const prisma = new PrismaService(new ConfigService(process.env));
    await prisma.$connect();
    const rollback = new Error('ROLLBACK_PLATFORM');
    try {
      await expect(prisma.$transaction(async tx => {
        const db = new Proxy(tx, { get(obj, key) {
          if(key === '$transaction') return async (fn: (t: typeof tx) => unknown) => {
            await tx.$executeRawUnsafe('SAVEPOINT platform_test');
            try { const value = await fn(tx); await tx.$executeRawUnsafe('RELEASE SAVEPOINT platform_test'); return value; }
            catch(e) { await tx.$executeRawUnsafe('ROLLBACK TO SAVEPOINT platform_test'); await tx.$executeRawUnsafe('RELEASE SAVEPOINT platform_test'); throw e; }
          }; return Reflect.get(obj,key);
        }}) as PrismaService;
        const role = await tx.role.findUniqueOrThrow({where:{code:'SUPER_ADMIN'}});
        const root = await tx.user.create({data:{username:randomUUID(),name:'Platform test',passwordHash:'not-a-login',roles:{create:{roleId:role.id}}}});
        const actor:AuthUser={id:root.id,organizationId:null,name:root.name,username:root.username,roles:['SUPER_ADMIN'],permissions:[]};
        const svc = new PlatformService(db);
        const dto={name:'Test company',code:`test-${randomUUID().slice(0,8)}`,ownerName:'Owner',username:randomUUID(),password:'Temporary-test-2026'};
        const company=await svc.create(actor,dto);
        const owner=await tx.user.findUniqueOrThrow({where:{id:company.ownerId},include:{roles:{include:{role:true}}}});
        expect(owner.organizationId).toBe(company.id);
        expect(owner.roles.map(r=>r.role.code)).toEqual(['NATIONAL_MANAGER']);
        expect(await bcrypt.compare(dto.password,owner.passwordHash)).toBe(true);
        const ownerAuth={...actor,id:owner.id,organizationId:company.id};
        await expect(svc.list(ownerAuth)).rejects.toThrow('للسوبر أدمن');
        await expect(svc.saveBranding(ownerAuth,company.id,{...defaultBranding,revision:0})).rejects.toThrow();
        expect((await svc.ownBranding(ownerAuth)).displayName).toBe(dto.name);
        const theme={...defaultBranding,displayName:'Company identity',primary:'#234567',style:'SQUARE',layout:'ATLAS',revision:0};
        await svc.saveBranding(actor,company.id,theme);
        expect(await svc.ownBranding(ownerAuth)).toMatchObject({displayName:theme.displayName,primary:theme.primary,layout:'ATLAS',revision:1});
        await expect(svc.saveBranding(actor,company.id,theme)).rejects.toThrow('جلسة أخرى');
        const other=await svc.create(actor,{...dto,code:`other-${randomUUID().slice(0,8)}`,username:randomUUID()});
        expect((await svc.ownBranding({...ownerAuth,organizationId:other.id})).primary).toBe(defaultBranding.primary);
        await expect(svc.create(actor,{...dto,code:`dup-${randomUUID().slice(0,8)}`})).rejects.toThrow('مستخدم');
        expect(await tx.organization.count({where:{id:{in:[company.id,other.id]}}})).toBe(2);
        const setup=new CompanyService(db);
        const classification=await setup.createClass(ownerAuth,{code:'A',name:'Priority'});
        const cycleInput={name:'First cycle',startsOn:'2100-01-01',endsOn:'2100-01-31',frequency:[{id:classification.id,requiredVisits:3}],workingDays:Array.from({length:7},(_,weekday)=>({weekday,isWorking:weekday!==5}))};
        const firstCycle=await setup.createCycle(ownerAuth,cycleInput);
        expect((await setup.cycleOptions(ownerAuth)).cycles.map(c=>c.id)).toEqual([firstCycle.id]);
        expect(await tx.cycleClassRule.count({where:{cycleId:firstCycle.id,requiredVisits:3}})).toBe(1);
        expect(await tx.cycleWorkingDayRule.count({where:{cycleId:firstCycle.id}})).toBe(7);
        await expect(setup.createCycle(ownerAuth,{...cycleInput,name:'Overlap'})).rejects.toThrow('تتداخل');
        await expect(setup.createCycle(ownerAuth,{...cycleInput,startsOn:'2100-02-30'})).rejects.toThrow();
        await expect(setup.createCycle(ownerAuth,{...cycleInput,workingDays:cycleInput.workingDays.map(d=>({...d,isWorking:false}))})).rejects.toThrow();
        await expect(setup.createCycle({...ownerAuth,id:other.ownerId,organizationId:other.id},cycleInput)).rejects.toThrow('تصنيفات');
        const specialty=await setup.catalog(ownerAuth,'specialties',{name:'Cardiology'});
        const product=await setup.catalog(ownerAuth,'products',{name:'Product A'});
        expect(await setup.catalog(ownerAuth,'products',{name:'Product B'},product.id)).toEqual({id:product.id,name:'Product B'});
        await expect(setup.catalog(ownerAuth,'products',{name:'product b'})).rejects.toThrow('موجود');
        await expect(setup.catalog({...ownerAuth,id:other.ownerId,organizationId:other.id},'products',{name:'Invalid'},product.id)).rejects.toThrow();
        expect((await setup.workspace(ownerAuth)).specialties.map(s=>s.id)).toEqual([specialty.id]);
        const province=await setup.province(ownerAuth,{name:'New province'});
        const teamManager=await setup.manager(ownerAuth,{name:'New team manager',username:randomUUID(),password:'Manager-test-2026'});
        const teamInput={name:'First RX',provinceId:province.id,managerId:teamManager.id,specialtyIds:[],productIds:[]};
        const createdTeam=await setup.team(ownerAuth,teamInput);
        expect((await setup.workspace(ownerAuth)).teams.map(t=>t.id)).toEqual([createdTeam.id]);
        const managerAuth={...ownerAuth,id:teamManager.id,roles:['TEAM_MANAGER']};
        await expect(setup.createCycle(managerAuth,cycleInput)).rejects.toThrow();
        await expect(setup.catalog(managerAuth,'specialties',{name:'Denied'})).rejects.toThrow();
        expect((await new ManagerService(db).workspace(managerAuth)).teams.map(t=>t.id)).toEqual([createdTeam.id]);
        await expect(setup.province(managerAuth,{name:'Denied province'})).rejects.toThrow();
        const otherOwnerAuth={...ownerAuth,id:other.ownerId,organizationId:other.id};
        await expect(setup.editManager(otherOwnerAuth,teamManager.id,{name:'Denied',username:randomUUID()})).rejects.toThrow();
        await expect(setup.changeTeamManager(otherOwnerAuth,createdTeam.id,{managerId:teamManager.id,expectedManagerIds:[teamManager.id]})).rejects.toThrow();
        await expect(setup.editManager(ownerAuth,teamManager.id,{name:'Duplicate',username:dto.username})).rejects.toThrow('مستخدم');
        expect((await setup.workspace(otherOwnerAuth)).teams).toEqual([]);
        await expect(setup.team(otherOwnerAuth,teamInput)).rejects.toThrow();
        const otherProvince=await setup.province(otherOwnerAuth,{name:'Other province'});
        const areas=new AreaManagementService(db);
        const areaOwner={...ownerAuth,roles:['NATIONAL_MANAGER'],permissions:['areas.manage','areas.manage_own']};
        expect((await areas.catalog(areaOwner)).provinces.map(p=>p.id)).toEqual([province.id]);
        const group=await areas.save(areaOwner,{name:'West',provinceId:province.id},'group');
        const managedArea=await areas.save(areaOwner,{name:'District',provinceId:province.id,groupId:group.id},'area');
        await areas.save(areaOwner,{name:'Updated district',provinceId:province.id,groupId:group.id},'area',managedArea.id);
        expect((await areas.catalog(areaOwner)).areas).toMatchObject([{id:managedArea.id,name:'Updated district',groupId:group.id}]);
        await expect(areas.save(areaOwner,{name:'Denied',provinceId:otherProvince.id},'area')).rejects.toThrow();
        await expect(areas.catalog({...areaOwner,id:teamManager.id})).rejects.toThrow();
        const targets=new TargetManagementService(db);
        const targetOwner={...areaOwner,permissions:[...areaOwner.permissions,'targets.view','targets.manage']};
        const targetInput={type:'DOCTOR' as const,name:'Owner doctor',areaId:managedArea.id,targetClassId:classification.id,specialtyId:specialty.id};
        const added=await targets.save(targetOwner,targetInput);
        await targets.save(targetOwner,{...targetInput,name:'Updated owner doctor'},added.id);
        expect((await targets.list(targetOwner,'DOCTOR')).items).toMatchObject([{id:added.id,name:'Updated owner doctor'}]);
        const exported=await targets.exportDoctors(targetOwner);
        expect(exported.length).toBeGreaterThan(0);
        await expect(targets.options({...targetOwner,id:teamManager.id})).rejects.toThrow();
        await expect(targets.save({...targetOwner,id:other.ownerId,organizationId:other.id},targetInput)).rejects.toThrow();
        await expect(setup.team(ownerAuth,{...teamInput,name:'Invalid scope',provinceId:otherProvince.id})).rejects.toThrow();
        expect(await tx.team.count({where:{organizationId:company.id}})).toBe(1);
        const recurring=new RecurringCycleService(db);
        const schedule={mode:'MONTH_AND_HALF' as const,length:1,frequency:cycleInput.frequency,workingDays:cycleInput.workingDays};
        await recurring.save(ownerAuth,schedule,schedule);
        const active=await tx.cycle.findFirstOrThrow({where:{organizationId:company.id,id:{not:firstCycle.id}}});
        const repRole=await tx.role.findUniqueOrThrow({where:{code:'REP'}});
        const rep=await tx.user.create({data:{organizationId:company.id,username:randomUUID(),name:'Recurring rep',passwordHash:'not-a-login',roles:{create:{roleId:repRole.id}}}});
        await tx.teamMember.create({data:{teamId:createdTeam.id,userId:rep.id}});
        const area=await tx.area.create({data:{organizationId:company.id,provinceId:province.id,name:'Recurring area'}});
        const target=await tx.fieldTarget.create({data:{organizationId:company.id,name:'Recurring doctor',type:'DOCTOR',targetClassId:classification.id,locations:{create:{areaId:area.id}},specialties:{create:{specialtyId:specialty.id}}}});
        const profile=await tx.repCycleProfile.create({data:{organizationId:company.id,cycleId:active.id,repId:rep.id,dailyVisitTarget:8,teamPeriods:{create:{teamId:createdTeam.id,startedAt:active.startsAt,endedAt:active.endsAt,scopeConfigured:true,scopeAreas:{create:{areaId:area.id}},scopeProducts:{create:{productId:product.id}},scopeSpecialties:{create:{specialtyId:specialty.id}}}}}});
        const nextDay=new Date(+active.endsAt+86400000+12*3600000);
        const updatedSchedule={...schedule,frequency:[{id:classification.id,requiredVisits:5}]};
        await recurring.save(ownerAuth,updatedSchedule,updatedSchedule);
        expect((await tx.cycleClassRule.findFirstOrThrow({where:{cycleId:active.id}})).requiredVisits).toBe(3);
        await tx.repCycleTeamPeriod.updateMany({where:{repCycleProfileId:profile.id},data:{scopeConfigured:false}});
        const cycleCount=await tx.cycle.count({where:{organizationId:company.id}});
        await expect(recurring.ensure(company.id,nextDay)).rejects.toThrow('يحتاج تحديد نطاقه');
        expect(await tx.cycle.count({where:{organizationId:company.id}})).toBe(cycleCount);
        await tx.repCycleTeamPeriod.updateMany({where:{repCycleProfileId:profile.id},data:{scopeConfigured:true}});
        await recurring.ensure(company.id,nextDay);
        await recurring.ensure(company.id,nextDay);
        const nextProfiles=await tx.repCycleProfile.findMany({where:{organizationId:company.id,repId:rep.id},include:{targets:true,teamPeriods:true}});
        expect(nextProfiles).toHaveLength(2);
        const moved=nextProfiles.find(p=>p.id!==profile.id)!;
        expect(moved.targets).toMatchObject([{targetId:target.id,requiredVisits:5}]);
        expect(moved.teamPeriods).toHaveLength(1);
        expect(await tx.visit.count({where:{repCycleProfileId:moved.id}})).toBe(0);
        expect(await tx.repCycleProfile.findUnique({where:{id:profile.id}})).not.toBeNull();
        await expect(recurring.save(managerAuth,schedule,schedule)).rejects.toThrow();
        await expect(recurring.save({...ownerAuth,id:other.ownerId,organizationId:other.id},schedule,schedule)).rejects.toThrow();
        const otherClass=await setup.createClass(otherOwnerAuth,{code:'A',name:'Other priority'});
        const otherYear=(await recurring.options(otherOwnerAuth)).year;
        await tx.cycle.create({data:{organizationId:other.id,name:'Blocking draft',timezone:'Asia/Damascus',startsAt:new Date(`${otherYear}-01-01T00:00:00Z`),endsAt:new Date(`${otherYear}-12-31T00:00:00Z`),status:'DRAFT'}});
        const otherSchedule={...schedule,frequency:[{id:otherClass.id,requiredVisits:2}]};
        await expect(recurring.save(otherOwnerAuth,otherSchedule,otherSchedule)).rejects.toThrow('يتداخل');
        expect((await tx.organizationSettings.findUniqueOrThrow({where:{organizationId:other.id}})).cycleSchedule).toBeNull();
        const audit=await tx.auditLog.findMany({where:{organizationId:company.id}});
        expect(JSON.stringify(audit)).not.toContain(dto.password);
        expect(JSON.stringify(await svc.list(actor))).not.toContain('passwordHash');
        for (const layout of ['CLASSIC','ATLAS','DIWAN','PEARL']) expect(validateSync(Object.assign(new BrandingDto(),theme,{layout}))).toHaveLength(0);
        expect(validateSync(Object.assign(new BrandingDto(),theme,{layout:'arbitrary-css'})).length).toBeGreaterThan(0);
        const bad=Object.assign(new BrandingDto(),theme,{primary:'url(javascript:bad)',logo:'data:image/svg+xml;base64,AAAA'});
        expect(validateSync(bad).length).toBeGreaterThan(0);
        await tx.userRole.deleteMany({where:{userId:root.id}});
        await expect(svc.list(actor)).rejects.toThrow();
        throw rollback;
      },{timeout:20000})).rejects.toBe(rollback);
    } finally { await prisma.$disconnect(); }
  });
});
