import ExcelJS from 'exceljs';
import 'dotenv/config';
import { describe,it,expect } from 'vitest';
import { randomUUID } from 'node:crypto';
import { ConfigService } from '@nestjs/config';
import { JwtService } from '@nestjs/jwt';
import { PrismaService } from '../src/database/prisma.service.js';
import { AuthService } from '../src/auth/auth.service.js';
import { PlatformService } from '../src/platform/platform.service.js';
import { CompanyService } from '../src/company/company.service.js';
import { AreaManagementService } from '../src/manager/area-management.service.js';
import { TargetManagementService } from '../src/manager/target-management.service.js';
import { RepManagementService } from '../src/manager/rep-management.service.js';
import { RecurringCycleService } from '../src/cycles/recurring-cycle.service.js';
import { RepWorkspaceService } from '../src/rep/rep-workspace.service.js';
import { ManagerService } from '../src/manager/manager.service.js';
import type { AuthUser } from '../src/auth/auth.types.js';

describe.skipIf(process.env.RUN_DB_TESTS!=='1')('new company operational flow',()=>{
 it('provisions, signs in, assigns, registers and reports a visit using real services, then rolls back',async()=>{
  const config=new ConfigService(process.env),prisma=new PrismaService(config);await prisma.$connect();
  const rollback=new Error('ROLLBACK_ONBOARDING');const code=`onboard-${randomUUID().slice(0,24)}`;
  try{
   await expect(prisma.$transaction(async tx=>{
    let sequence=0;
    const db=new Proxy(tx,{get(obj,key){if(key==='$transaction')return async(fn:(db:typeof tx)=>unknown)=>{const point=`flow_${++sequence}`;await tx.$executeRawUnsafe(`SAVEPOINT ${point}`);try{const result=await fn(tx);await tx.$executeRawUnsafe(`RELEASE SAVEPOINT ${point}`);return result;}catch(e){await tx.$executeRawUnsafe(`ROLLBACK TO SAVEPOINT ${point}`);await tx.$executeRawUnsafe(`RELEASE SAVEPOINT ${point}`);throw e;}};return Reflect.get(obj,key);}}) as PrismaService;
    const rootRole=await tx.role.findUniqueOrThrow({where:{code:'SUPER_ADMIN'}});
    const root=await tx.user.create({data:{username:randomUUID(),name:'Fixture platform admin',passwordHash:'not-a-login',roles:{create:{roleId:rootRole.id}}}});
    const rootAuth:AuthUser={id:root.id,name:root.name,username:root.username,organizationId:null,roles:['SUPER_ADMIN'],permissions:[]};
    const platform=new PlatformService(db),company=new CompanyService(db),auth=new AuthService(db,new JwtService(),config);
    const password='Onboarding-test-2026',ownerUsername=randomUUID();
    const organization=await platform.create(rootAuth,{name:'Isolated onboarding company',code,ownerName:'Owner',username:ownerUsername,password});
    const owner=(await auth.login({username:ownerUsername,password})).user;
    expect(owner.organizationId).toBe(organization.id);
    const province=await company.province(owner,{name:'Province'});
    const specialty=await company.catalog(owner,'specialties',{name:'Cardiology'});
    const product=await company.catalog(owner,'products',{name:'Product'});
    const classification=await company.createClass(owner,{code:'A',name:'Priority'});
    const areas=new AreaManagementService(db);
    const group=await areas.save(owner,{name:'West',provinceId:province.id},'group');
    const area=await areas.save(owner,{name:'District',provinceId:province.id,groupId:group.id},'area');
    const schedule={mode:'MONTH_AND_HALF' as const,length:1,frequency:[{id:classification.id,requiredVisits:3}],workingDays:Array.from({length:7},(_,weekday)=>({weekday,isWorking:true}))};
    await new RecurringCycleService(db).save(owner,schedule,schedule);
    const managerUsername=randomUUID();
    const managerAccount=await company.manager(owner,{name:'Manager',username:managerUsername,password});
    const manager=(await auth.login({username:managerUsername,password})).user;
    const team=await company.team(owner,{name:'RX1',provinceId:province.id,managerId:managerAccount.id,specialtyIds:[specialty.id],productIds:[product.id]});
    const targets=new TargetManagementService(db);
    const doctor=await targets.save(owner,{type:'DOCTOR',name:'Doctor',areaId:area.id,targetClassId:classification.id,specialtyId:specialty.id});
    const repUsername=randomUUID();
    const createdRep=await new RepManagementService(db).create(owner,{name:'Rep',username:repUsername,password,teamId:team.id,areaIds:[area.id],specialtyIds:[specialty.id],productIds:[product.id],dailyVisitTarget:8});
    expect(createdRep.targetCount).toBe(1);
    const rep=(await auth.login({username:repUsername,password})).user;
    const repService=new RepWorkspaceService(db),workspace=await repService.workspace(rep);
    expect(workspace.cycle).not.toBeNull();
    expect((await repService.targets(rep,{type:'DOCTOR'})).items.map(t=>t.id)).toEqual([doctor.id]);
    const input={clientRef:randomUUID(),cycleId:workspace.cycle!.id,type:'DOCTOR' as const,areaIds:[area.id],targetIds:[doctor.id],productIds:[product.id],visitDate:workspace.cycle!.today,notes:'Onboarding integration test'};
    await tx.organizationSettings.update({where:{organizationId:organization.id},data:{roundLocationPolicy:'REQUIRED'}});
    expect((await repService.workspace(rep)).roundLocationPolicy).toBe('REQUIRED');
    await expect(repService.register(rep,input)).rejects.toThrow('إلزامي');
    await expect(repService.register(rep,{...input,latitude:36,longitude:37,accuracy:20,locationCapturedAt:'2020-01-01T00:00:00Z'})).rejects.toThrow('قديم');
    await tx.organizationSettings.update({where:{organizationId:organization.id},data:{roundLocationPolicy:'OPTIONAL'}});
    await expect(repService.register(rep,input)).rejects.toThrow('سبب');
    await tx.organizationSettings.update({where:{organizationId:organization.id},data:{roundLocationPolicy:'REQUIRED'}});
    const saved=await repService.register(rep,{...input,latitude:36,longitude:37,accuracy:20,locationCapturedAt:new Date().toISOString()});
    expect((await tx.fieldRound.findUniqueOrThrow({where:{id:saved.id}})).registrationLocation).toMatchObject({status:'CAPTURED',latitude:36,longitude:37,accuracy:20});
    await tx.organizationSettings.update({where:{organizationId:organization.id},data:{roundLocationPolicy:'DISABLED'}});
    expect((await repService.register(rep,input)).id).toBe(saved.id);
    expect((await repService.history(rep)).items.some(r=>r.roundId===saved.id)).toBe(true);
    const managerView=await new ManagerService(db).workspace(manager);
    expect(managerView.summary.visits).toBe(1);
    expect(managerView.rounds.some(r=>r.visits.some(v=>v.roundId===saved.id))).toBe(true);
    const coverage=await company.coverage(owner);
    expect(coverage.physicalVisits).toBe(1);
    expect(coverage.provinces.find(p=>p.id===province.id)).toMatchObject({physicalVisits:1,required:3,remaining:2,coverage:33});
    expect((await company.workspace(owner)).reps.map(r=>r.id)).toContain(rep.id);
    // Adding a matching doctor after assignment must immediately reach the rep's existing scope.
    const lateDoctor=await targets.save(owner,{type:'DOCTOR',name:'Later doctor',areaId:area.id,targetClassId:classification.id,specialtyId:specialty.id});
    expect((await repService.targets(rep,{type:'DOCTOR'})).items.map(t=>t.id)).toContain(lateDoctor.id);
    const newUsername=randomUUID();
    await company.editManager(owner,managerAccount.id,{name:'Renamed manager',username:newUsername});
    await expect(auth.login({username:managerUsername,password})).rejects.toThrow();
    expect((await auth.login({username:newUsername,password})).user.id).toBe(managerAccount.id);
    const successorUsername=randomUUID();
    const successorAccount=await company.manager(owner,{name:'Successor',username:successorUsername,password});
    await expect(company.changeTeamManager(manager,team.id,{managerId:successorAccount.id,expectedManagerIds:[managerAccount.id]})).rejects.toThrow();
    await company.changeTeamManager(owner,team.id,{managerId:successorAccount.id,expectedManagerIds:[managerAccount.id]});
    const successor=(await auth.login({username:successorUsername,password})).user;
    expect((await new ManagerService(db).workspace(successor)).summary.visits).toBe(1);
    expect((await new ManagerService(db).workspace(manager)).teams).toHaveLength(0);
    expect(await tx.visit.count({where:{roundId:saved.id}})).toBe(1);
    expect((await tx.teamMember.findFirstOrThrow({where:{teamId:team.id,userId:managerAccount.id,isManager:true}})).endedAt).not.toBeNull();
    await expect(company.changeTeamManager(owner,team.id,{managerId:managerAccount.id,expectedManagerIds:[managerAccount.id]})).rejects.toThrow('تغير');
    await company.changeTeamManager(owner,team.id,{managerId:successorAccount.id,expectedManagerIds:[successorAccount.id]});
    expect(await tx.teamMember.count({where:{teamId:team.id,isManager:true,endedAt:null}})).toBe(1);
    // Bulk deletion hides the catalog target, while preserving the recorded round and credits.
    const pharmacy=await targets.save(owner,{type:'PHARMACY',name:'Pharmacy',areaId:area.id,targetClassId:classification.id});
    const hospital=await targets.save(owner,{type:'HOSPITAL',name:'Hospital',areaId:area.id,targetClassId:classification.id});
    await expect(targets.deleteMany(owner,{type:'DOCTOR',ids:[doctor.id,pharmacy.id]})).rejects.toThrow();
    expect((await tx.fieldTarget.findUniqueOrThrow({where:{id:doctor.id}})).deletedAt).toBeNull();
    await expect(targets.deleteMany(manager,{type:'DOCTOR',ids:[doctor.id]})).rejects.toThrow();
    const beforeDeleteCoverage=await company.coverage(owner);
    expect(await targets.deleteMany(successor,{type:'DOCTOR',ids:[doctor.id,lateDoctor.id]})).toEqual({deleted:2});
    expect((await targets.list(owner,'DOCTOR')).items).toHaveLength(0);
    expect((await repService.targets(rep,{type:'DOCTOR'})).items).toHaveLength(0);
    expect((await repService.history(rep)).items.some(r=>r.roundId===saved.id)).toBe(true);
    expect((await new ManagerService(db).workspace(successor)).summary.visits).toBe(1);
    expect(await company.coverage(owner)).toEqual(beforeDeleteCoverage);
    expect(await tx.visit.count({where:{roundId:saved.id}})).toBe(1);
    await expect(repService.register(rep,{...input,clientRef:randomUUID()})).rejects.toThrow();
    await expect(targets.deleteMany(owner,{type:'DOCTOR',ids:[doctor.id]})).rejects.toThrow();
    expect(await targets.deleteMany(owner,{type:'PHARMACY',ids:[pharmacy.id]})).toEqual({deleted:1});
    expect(await targets.deleteMany(owner,{type:'HOSPITAL',ids:[hospital.id]})).toEqual({deleted:1});
    expect(await tx.auditLog.count({where:{organizationId:organization.id,entityType:'FieldTarget',action:'DELETE'}})).toBe(4);
    async function uploadRows(rows:string[][]) {
      const book=new ExcelJS.Workbook(),sheet=book.addWorksheet('Sheet1');
      sheet.addRow(['Name','City','Specailist','Classification','Doctor geo name']);
      rows.forEach(row=>sheet.addRow(row));
      return {originalname:'import.xlsx',buffer:Buffer.from(await book.xlsx.writeBuffer())};
    }
    const otherImportProvince=await company.province(owner,{name:'Second province'});
    expect((await targets.options(owner,otherImportProvince.id)).areas).toHaveLength(0);
    expect((await targets.list(owner,'DOCTOR',otherImportProvince.id)).items).toHaveLength(0);
    await expect(targets.save(owner,{type:'DOCTOR',name:'Wrong province',areaId:area.id,targetClassId:classification.id,specialtyId:specialty.id},undefined,otherImportProvince.id)).rejects.toThrow();
    await expect(targets.importDoctors(owner,await uploadRows([['Wrong city','Province','Cardiology','A','No cross province']]),otherImportProvince.id)).rejects.toThrow();
    expect(await tx.area.count({where:{organizationId:organization.id,name:'No cross province'}})).toBe(0);
    expect(await targets.importDoctors(owner,await uploadRows([['Selected province','','Cardiology','A','Scoped new area']]),otherImportProvince.id)).toEqual({imported:1,updated:0,replayed:false});
    expect((await tx.area.findFirstOrThrow({where:{organizationId:organization.id,name:'Scoped new area'}})).provinceId).toBe(otherImportProvince.id);
    const importFile=await uploadRows([['Import One','Province','جراحة أوعية','A','منطقة جديدة'],['Import Two','Province','جراحة أوعية','A','منطقة جديدة']]);
    expect(await targets.importDoctors(owner,importFile)).toEqual({imported:2,updated:0,replayed:false});
    const newArea=await tx.area.findFirstOrThrow({where:{organizationId:organization.id,name:'منطقة جديدة'}});
    const newSpecialty=await tx.specialty.findFirstOrThrow({where:{organizationId:organization.id,name:'جراحة أوعية'}});
    expect(await tx.area.count({where:{organizationId:organization.id,name:'منطقة جديدة'}})).toBe(1);
    expect(await tx.specialty.count({where:{organizationId:organization.id,name:'جراحة أوعية'}})).toBe(1);
    expect(await tx.fieldTarget.count({where:{organizationId:organization.id,locations:{some:{areaId:newArea.id}},specialties:{some:{specialtyId:newSpecialty.id}}}})).toBe(2);
    const filteredExport = new ExcelJS.Workbook();
    await filteredExport.xlsx.load(await targets.exportDoctors(owner,false,'','',undefined,JSON.stringify([newSpecialty.id])));
    expect(filteredExport.getWorksheet('Doctors')!.rowCount).toBe(3);
    expect(filteredExport.getWorksheet('Doctors')!.getRow(2).getCell(5).value).toBe(newSpecialty.id);
    const orderedExport = new ExcelJS.Workbook();
    await orderedExport.xlsx.load(await targets.exportDoctors(owner,false,'','',undefined,JSON.stringify([newSpecialty.id,specialty.id])));
    expect(orderedExport.getWorksheet('Doctors')!.getRow(4).getCell(5).value).toBe(specialty.id);
    const emptyExport = new ExcelJS.Workbook();
    await emptyExport.xlsx.load(await targets.exportDoctors(owner,false,'','',undefined,'[]'));
    expect(emptyExport.getWorksheet('Doctors')!.rowCount).toBe(1);
    await expect(targets.exportDoctors(owner,false,'','',undefined,'["invalid"]')).rejects.toThrow();
    expect(await targets.importDoctors(owner,importFile)).toEqual({imported:0,updated:0,replayed:true});
    expect(await targets.importDoctors(owner,await uploadRows([['Normalized','Province','جراحة اوعية','A','المنطقة جديدة']]))).toEqual({imported:1,updated:0,replayed:false});
    await expect(targets.importDoctors(owner,await uploadRows([['Will rollback','Province','Temporary specialty','A','Temporary area'],['Invalid','Province','Temporary specialty','UNKNOWN','Temporary area']]))).rejects.toThrow();
    expect(await tx.area.count({where:{organizationId:organization.id,name:'Temporary area'}})).toBe(0);
    expect(await tx.specialty.count({where:{organizationId:organization.id,name:'Temporary specialty'}})).toBe(0);
    await expect(targets.importDoctors(successor,await uploadRows([['Denied','Province','No permission specialty','A','منطقة جديدة']]))).rejects.toThrow();
    const audit=await tx.auditLog.findMany({where:{organizationId:organization.id}});
    expect(JSON.stringify(audit)).not.toContain(password);
    throw rollback;
   },{timeout:30000})).rejects.toBe(rollback);
   expect(await prisma.organization.findUnique({where:{code}})).toBeNull();
  }finally{await prisma.$disconnect();}
 },40000);
});
